enum class ItemCategory {
  WEAPON,
  AMMO,
  CONSUMABLE,
  UTILITY,
  GEAR,
}

enum class EquipmentSlot(val key: String, val label: String) {
  HEAD("head", "Head"),
  VEST("vest", "Vest"),
  BODY("body", "Body"),
  BACK("back", "Back"),
  LEGS("legs", "Legs"),
  FEET("feet", "Feet"),
}

data class WeaponStats(
  val damage: Float,
  val fireRateSec: Float,
  val rangeMeters: Float,
  val noiseRadius: Float,
  val recoilKick: Float,
  val spreadDeg: Float,
  val magCapacity: Int,
  val ammoItemId: String?,
  val isAutomatic: Boolean,
  val isMelee: Boolean = false,
)

